    /**
     * Run the database seeds.
     *
     * @return array{books: int, copies: int, skipped: int}
     */
    public function run(): array
    {
        return $this->seedCatalog();
    }

    /**
     * Seed catalog records directly into the SQL database.
     *
     * @return array{books: int, copies: int, skipped: int}
     */
    public function seedCatalog(): array
    {
        $csvPath = database_path('data/books.csv');
        if (file_exists($csvPath) && is_readable($csvPath)) {
            $importService = app(BookImportService::class);
            $summary = $importService->importFromCsv($csvPath);

            return [
                'books' => $summary['books'],
                'copies' => $summary['copies'],
                'skipped' => $summary['skipped'],
            ];
        }

        $records = $this->catalogData();
        $summary = ['books' => 0, 'copies' => 0, 'skipped' => 0];

        foreach ($records as $record) {
            if (! $this->isValidRecord($record)) {
                $summary['skipped']++;

                continue;
            }

            $result = DB::transaction(fn (): array => $this->persistRecord($record));

            $summary['books'] += $result['book_created'] ? 1 : 0;
            $summary['copies'] += $result['copies_created'];
        }

        return $summary;
    }

    /**
     * @param  array<string, mixed>  $record
     */
    private function isValidRecord(array $record): bool
    {
        return filled($record['title'] ?? null)
            && filled($record['authors'] ?? null)
            && filled($record['categories'] ?? null);
    }

    /**
     * @param  array<string, mixed>  $record
     * @return array{book_created: bool, copies_created: int}
     */
    private function persistRecord(array $record): array
    {
        $publisher = $this->publisher($record['publisher'] ?: 'Project Gutenberg');
        $lookup = $this->bookLookup($record);

        $book = Book::query()->firstOrNew($lookup);
        $bookCreated = ! $book->exists;

        $book->fill([
            'publisher_id' => $publisher->id,
            'title' => $record['title'],
            'subtitle' => $record['subtitle'] ?: null,
            'slug' => $this->uniqueSlug(Book::class, $record['title'], $book->id),
            'isbn_10' => $record['isbn_10'] ?: null,
            'isbn_13' => $record['isbn_13'] ?: null,
            'description' => $record['description'] ?: null,
            'language' => $record['language'] ?: 'en',
            'publication_year' => $record['publication_year'] ? (int) $record['publication_year'] : null,
            'edition' => $record['edition'] ?: 'Public domain edition',
            'page_count' => $record['page_count'] ? (int) $record['page_count'] : null,
            'cover_image_path' => $record['cover_image_path'] ?: null,
            'average_rating' => $record['average_rating'] ? (float) $record['average_rating'] : 0,
            'ratings_count' => $record['ratings_count'] ? (int) $record['ratings_count'] : 0,
            'source' => $record['source'] ?: 'Project Gutenberg',
            'source_identifier' => $record['source_identifier'] ?: null,
            'source_url' => $record['source_url'] ?: null,
            'metadata' => [
                'source' => $record['source'] ?: 'Project Gutenberg',
                'source_identifier' => $record['source_identifier'] ?: null,
                'source_url' => $record['source_url'] ?: null,
            ],
        ])->save();

        $book->authors()->sync($this->authors($record['authors'])->modelKeys());
        $book->categories()->sync($this->categories($record['categories'])->modelKeys());

        return [
            'book_created' => $bookCreated,
            'copies_created' => $this->ensureCopies($book, (int) ($record['copies'] ?: 1)),
        ];
    }

    /**
     * @param  array<string, mixed>  $record
     * @return array<string, string>
     */
    private function bookLookup(array $record): array
    {
        if (filled($record['isbn_13'] ?? null)) {
            return ['isbn_13' => $record['isbn_13']];
        }

        if (filled($record['isbn_10'] ?? null)) {
            return ['isbn_10' => $record['isbn_10']];
        }

        return [
            'source' => $record['source'] ?: 'Project Gutenberg',
            'source_identifier' => $record['source_identifier'] ?: Str::slug($record['title']),
        ];
    }

    private function publisher(string $name): Publisher
    {
        return Publisher::query()->firstOrCreate(
            ['slug' => Str::slug($name)],
            ['name' => $name]
        );
    }

    /**
     * @return Collection<int, Author>
     */
    private function authors(string $authors): Collection
    {
        return Author::query()->whereIn('id', collect(explode(';', $authors))
            ->map(fn (string $name): Author => Author::query()->firstOrCreate(
                ['slug' => Str::slug($name)],
                ['name' => trim($name)]
            ))
            ->pluck('id')
            ->all())->get();
    }

    /**
     * @return Collection<int, Category>
     */
    private function categories(string $categories): Collection
    {
        return Category::query()->whereIn('id', collect(explode(';', $categories))
            ->map(fn (string $name): Category => Category::query()->firstOrCreate(
                ['slug' => Str::slug($name)],
                ['name' => trim($name)]
            ))
            ->pluck('id')
            ->all())->get();
    }

    private function ensureCopies(Book $book, int $targetCopies): int
    {
        $created = 0;

        for ($copyNumber = $book->copies()->count() + 1; $copyNumber <= $targetCopies; $copyNumber++) {
            $book->copies()->create([
                'barcode' => sprintf('RO-%05d-%02d', $book->id, $copyNumber),
                'status' => BookCopy::STATUS_AVAILABLE,
                'location' => 'Main Library Stack '.chr(64 + (($book->id % 5) + 1)),
                'condition' => 'good',
                'acquisition_date' => now()->subDays($book->id + $copyNumber)->toDateString(),
            ]);

            $created++;
        }

        return $created;
    }

    private function uniqueSlug(string $modelClass, string $value, ?int $ignoreId = null): string
    {
        $baseSlug = Str::slug($value);
        $slug = $baseSlug;
        $counter = 2;

        while ($modelClass::query()
            ->where('slug', $slug)
            ->when($ignoreId, fn ($query): mixed => $query->whereKeyNot($ignoreId))
            ->exists()) {
            $slug = "{$baseSlug}-{$counter}";
            $counter++;
        }

        return $slug;
    }

